import { customType, timestamp, uuid } from "drizzle-orm/pg-core";

/**
 * Exact decimal stored as Postgres `numeric`, surfaced to the app as a JS number.
 *
 * Money and rates are stored without a fixed scale so the database keeps
 * exactly what the services compute (they already round to 2 dp where it
 * matters) and sums/increments done in SQL are exact. node-postgres returns
 * numeric as a string; it is parsed back to a number here so services keep
 * doing arithmetic on plain numbers.
 */
export const decimal = customType<{ data: number; driverData: string }>({
    dataType() {
        return "numeric";
    },
    fromDriver(value: string | number): number {
        return typeof value === "number" ? value : Number(value);
    },
    toDriver(value: number): string {
        if (typeof value !== "number" || !Number.isFinite(value)) {
            throw new TypeError(`Expected a finite number for a numeric column, got ${String(value)}`);
        }
        return String(value);
    },
});

/** timestamptz surfaced as a JS Date */
export const timestamptz = (name: string) => timestamp(name, { withTimezone: true, mode: "date" });

/** uuid primary key generated by Postgres */
export const id = () => uuid("id").primaryKey().defaultRandom();

/** createdAt / updatedAt maintained the way Mongoose's `timestamps: true` did */
export const timestamps = () => ({
    createdAt: timestamptz("created_at").notNull().defaultNow(),
    updatedAt: timestamptz("updated_at")
        .notNull()
        .defaultNow()
        .$onUpdate(() => new Date()),
});
